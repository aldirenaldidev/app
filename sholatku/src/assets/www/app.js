function haversine(a1,o1,a2,o2){
  const R=6371,t=Math.PI/180;
  const dLa=(a2-a1)*t, dLo=(o2-o1)*t;
  const h=Math.pow(Math.sin(dLa/2),2)+Math.cos(a1*t)*Math.cos(a2*t)*Math.pow(Math.sin(dLo/2),2);
  return 2*R*Math.asin(Math.sqrt(h));
}
function nearestCity(lat, lon){
  let best=KOTA_LIST[0], bd=1e18;
  KOTA_LIST.forEach(k=>{ const d=haversine(lat,lon,k.lat,k.lon); if(d<bd){bd=d;best=k;} });
  return best;
}
