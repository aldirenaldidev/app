let compassTimer=null, qiblaDeg=0;
function qiblaBearing(lat, lon){
  const toR=Math.PI/180;
  const dLon=(KAABA.lon-lon)*toR, la1=lat*toR, la2=KAABA.lat*toR;
  const y=Math.sin(dLon), x=Math.cos(la1)*Math.tan(la2)-Math.sin(la1)*Math.cos(dLon);
  return (Math.atan2(y,x)/toR+360)%360;
}
