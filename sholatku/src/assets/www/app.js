/* ---------- onboarding 4 langkah ---------- */
const obRemState = {fardhu:true, dhuha:true, tahajud:true, puasa:true, pre15:true};
function obShow(n){
  [1,2,3,4].forEach(i=>{
    $("ob-s"+i).classList.toggle("active", i===n);
    $("ob-b"+i).classList.toggle("on", i<=n);
  });
  $("ob-step-label").textContent = "Langkah "+n+" dari 4";
}
function finishOnboardingFlow(){
  try{
    if(hasBridge("AndroidOnboard")) AndroidOnboard.finishOnboarding();
    lsSet("sk_onboard","1");
  }catch(e){}
  $("onboarding").classList.remove("show");
  document.body.classList.remove("onboarding");
  loadTimings(); loadForecast(); prefetchImsakiyah();
}
function applyObReminders(){
  SET.fardhu = obRemState.fardhu; SET.dhuha = obRemState.dhuha;
  SET.tahajud = obRemState.tahajud; SET.puasa = obRemState.puasa; SET.pre15 = obRemState.pre15;
  rescheduleAlarms();
}
function checkOnboarding(){
  let done = true;
  try{
    if(hasBridge("AndroidOnboard")) done = AndroidOnboard.isOnboardingDone();
    else done = lsGet("sk_onboard","0")==="1";
  }catch(e){ done = true; }
  if(done) return false;
  document.body.classList.add("onboarding");
  $("onboarding").classList.add("show");
  obShow(1);
  // Langkah 1: izin notifikasi
  const go2 = ()=>obShow(2);
  $("ob1-next").addEventListener("click",()=>{
    try{ if(hasBridge("AndroidAlarm")) AndroidAlarm.requestNotificationPermission(); }catch(e){}
    go2();
  });
  $("ob1-skip").addEventListener("click",go2);
  // Langkah 2: suara adzan
  renderAdzanList("ob-adzan-list");
  const subAuto = $("ob-subuh-auto");
  subAuto.classList.add("on");
  subAuto.addEventListener("click",()=>subAuto.classList.toggle("on"));
  const stopTest = ()=>{ try{ if(hasBridge("AndroidAlarm")) AndroidAlarm.stopAdzanTest(); }catch(e){} };
  const go3 = ()=>{ stopTest(); SET.subuhAuto = subAuto.classList.contains("on"); obShow(3); };
  $("ob2-next").addEventListener("click",go3);
  $("ob2-skip").addEventListener("click",go3);
  // Langkah 3: lokasi
  $("ob3-next").addEventListener("click",()=>{
    $("ob3-status").textContent = "Meminta izin lokasi…";
    try{
      if(hasBridge("AndroidOnboard")){
        AndroidOnboard.requestLocationPermission();
        setTimeout(()=>{ $("ob3-status").textContent = "Mencari lokasi…"; AndroidOnboard.fetchLocationOnce(); }, 700);
      }else{ selectCitySilent("Jakarta"); finishOnboardingFlow(); }
    }catch(e){ onLocationFailed(); }
  });
  $("ob3-manual").addEventListener("click",()=>{
    $("onboarding").classList.remove("show");
    document.body.classList.remove("onboarding");
    show("kota");
    // setelah pilih kota, selectCity() memanggil finishOnboardingFlow()
  });
  // Langkah 4: pengingat
  document.querySelectorAll("#ob-s4 .checkrow").forEach(r=>{
    r.addEventListener("click",()=>{
      r.classList.toggle("on");
      obRemState[r.dataset.rem] = r.classList.contains("on");
    });
  });
  $("ob4-done").addEventListener("click",()=>{
    applyObReminders();
    finishOnboardingFlow();
    toast("Selamat datang di SholatKu!");
  });
  return true;
}

