/* ---------- imsakiyah Ramadhan (v1/calendar + cache + fallback) ---------- */
let imsLoaded = false, imsFetching = false;
function imsCacheKey(c){ return "sk_imsakiyah_"+c.lat.toFixed(2)+"_"+c.lon.toFixed(2); }
function imsRender(days){
  const todayG = todayKey();
  let html = "";
  days.forEach((d,i)=>{
    const t = d.timings;
    const fmt = k => t[k].slice(0,5).replace(":",".");
    const subuh = fmt("Fajr");
    const imsak = minusMin(subuh, 10);
    const isToday = (d.gdate === todayG);
    html += '<tr class="'+(isToday?"today":"")+'"><td><b>'+(i+1)+'</b></td><td>'+imsak+'</td><td>'+subuh+'</td><td>'+fmt("Sunrise")+'</td><td>'+fmt("Dhuhr")+'</td><td>'+fmt("Asr")+'</td><td>'+fmt("Maghrib")+'</td><td>'+fmt("Isha")+'</td></tr>';
  });
  $("ims-body").innerHTML = html;
  $("ims-sub").textContent = locationLabel()+" • Metode Kemenag RI";
}
function imsReadCache(key){
  try{
    const raw = lsGet(key,"");
    if(!raw) return null;
    const o = JSON.parse(raw);
    if(!o.days || !o.days.length) return null;
    return o.days;
  }catch(e){ return null; }
}
function imsSaveCache(key, days){
  try{ lsSet(key, JSON.stringify({ts:Date.now(), days:days})); }catch(e){}
}
function imsDayObj(d){
  const h = d.date && d.date.hijri, g = d.date && d.date.gregorian;
  if(!h || !g || !h.month) return null;
  return {
    gdate: g.year+"-"+pad(parseInt(g.month.number,10))+"-"+pad(parseInt(g.day,10)),
    hijri9: (h.month.number==9),
    timings: d.timings
  };
}
function loadImsakiyah(){
  const c = cityCoords();
  const key = imsCacheKey(c);
  const cached = imsReadCache(key);
  if(cached){ imsRender(cached); imsLoaded = true; }
  else { $("ims-sub").textContent = locationLabel()+" • Metode Kemenag RI"; }
  imsFetch(c, key, !cached); // refresh background
}
function imsFetch(c, key, showLoading){
  if(imsFetching) return;
  imsFetching = true;
  if(showLoading) $("ims-body").innerHTML = '<tr><td colspan="8" style="color:var(--gray)">Memuat…</td></tr>';
  const now = new Date();
  const months = [];
  for(let i=0;i<13;i++){
    const dt = new Date(now.getFullYear(), now.getMonth()+i, 1);
    months.push([dt.getFullYear(), dt.getMonth()+1]);
  }
  let chain = Promise.resolve([]);
  months.forEach(m=>{
    chain = chain.then(acc=>{
      if(acc.filter(d=>d.hijri9).length >= 29) return acc; // Ramadan sudah lengkap
      const url = "https://api.aladhan.com/v1/calendar/"+m[0]+"/"+m[1]+"?latitude="+c.lat+"&longitude="+c.lon+"&method=20";
      return fetch(url).then(r=>r.json()).then(j=>{
        if(j && j.code===200 && j.data){
          j.data.forEach(d=>{ const o = imsDayObj(d); if(o) acc.push(o); });
        }
        return acc;
      }).catch(e=>acc);
    });
  });
  chain.then(acc=>{
    imsFetching = false;
    const ram = acc.filter(d=>d.hijri9).slice(0,30);
    if(ram.length >= 28){
      imsSaveCache(key, ram);
      imsRender(ram);
      imsLoaded = true;
    }else if(!imsLoaded){
      imsFallback(); // offline & tanpa cache -> data contoh
    }
  });
}
function imsFallback(){
  fetch("imsakiyah-sample.json").then(r=>r.json()).then(j=>{
    if(j && j.days && j.days.length){ imsRender(j.days); imsLoaded = true; }
    else imsEmpty();
  }).catch(e=>imsEmpty());
}
function imsEmpty(){
  $("ims-body").innerHTML = '<tr><td colspan="8" style="color:var(--gray)">Jadwal belum tersedia. Hubungkan internet sekali untuk mengunduh.</td></tr>';
}
/* download di awal: dipanggil setelah lokasi diketahui / app start */
function prefetchImsakiyah(){
  try{
    const c = cityCoords();
    const key = imsCacheKey(c);
    if(imsReadCache(key)) return; // sudah ada cache
    imsFetch(c, key, false);
  }catch(e){}
}
function minusMin(hm, m){
  const a = hm.split("."); const d = new Date();
  d.setHours(parseInt(a[0],10), parseInt(a[1],10)-m, 0, 0);
  return pad(d.getHours())+"."+pad(d.getMinutes());
}

